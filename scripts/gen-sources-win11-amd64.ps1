# Generate targets/win11-amd64/sources.cmake from the authoritative Visual Studio
# project files of the target copy. Run from the repository root or any directory:
#
#   powershell -ExecutionPolicy Bypass -File scripts/gen-sources-win11-amd64.ps1
#
# The x64 port keeps the engine TUs that the VS2010 projects build today, minus the
# MFC tool suite and the optional dependencies that are not part of this milestone:
#   * tools/** (MFC editors) except tools/compilers/** (plain C++: dmap, aas, renderbump, roqvq; needed by Common.cpp/renderer symbols)
#   * curl/**, MayaImport/**, openal/**, typeinfo/**
# SIMD asm TUs stay in the list: they are guarded for _M_IX86 inside the engine copy,
# so they compile to empty translation units on x64. Simd_AltiVec.cpp is excluded by
# the project itself (ExcludedFromBuild in every configuration) and is skipped here.

[CmdletBinding()]
param(
    [string]$Neo,
    [string]$OutFile
)

$ErrorActionPreference = 'Stop'

$ScriptDir = $PSScriptRoot
if ([string]::IsNullOrEmpty($ScriptDir)) {
    $ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
}
if ([string]::IsNullOrEmpty($Neo)) {
    $Neo = Join-Path $ScriptDir '..\targets\win11-amd64\doom3\neo'
}
if ([string]::IsNullOrEmpty($OutFile)) {
    $OutFile = Join-Path $ScriptDir '..\targets\win11-amd64\sources.cmake'
}

$Neo = (Resolve-Path -LiteralPath $Neo).Path
$OutFile = [System.IO.Path]::GetFullPath($OutFile)

function Get-ProjectSources {
    param(
        [Parameter(Mandatory = $true)][string]$Project,
        [Parameter(Mandatory = $true)][string]$ListName
    )

    $projectPath = Join-Path $Neo $Project
    if (-not (Test-Path -LiteralPath $projectPath)) {
        throw "Project file not found: $projectPath"
    }

    [xml]$xml = Get-Content -LiteralPath $projectPath
    $sources = New-Object 'System.Collections.Generic.List[string]'

    foreach ($node in $xml.GetElementsByTagName('ClCompile')) {
        $include = $node.GetAttribute('Include')
        if ([string]::IsNullOrWhiteSpace($include)) { continue }

        $rel = $include.Trim() -replace '\\', '/'

        # Honour project-wide exclusions (Simd_AltiVec.cpp is excluded in all 7 configurations).
        # A file excluded only from the Dedicated configurations (win_taskkeyhook.cpp) stays.
        $excludedNodes = @($node.ChildNodes | Where-Object { $_.LocalName -eq 'ExcludedFromBuild' })
        if ($excludedNodes.Count -ge 7) {
            $allExcluded = $true
            foreach ($excludedNode in $excludedNodes) {
                if ($excludedNode.InnerText.Trim() -ne 'true') { $allExcluded = $false }
            }
            if ($allExcluded) { continue }
        }

        if ($rel -match '^(curl|MayaImport|openal|typeinfo)/') { continue }
        if ($rel -match '^tools/' -and $rel -notmatch '^tools/compilers/') { continue }

        $full = Join-Path $Neo ($rel -replace '/', '\')
        if (-not (Test-Path -LiteralPath $full)) {
            throw "Source listed in ${Project} does not exist: $rel"
        }

        if (-not $sources.Contains($rel)) { $sources.Add($rel) }
    }

    Write-Host ("{0,-28} {1,4} TUs" -f $ListName, $sources.Count)
    return ,$sources
}

$idlibSources = Get-ProjectSources -Project 'idlib.vcxproj' -ListName 'IDLIB_SOURCES'
$engineSources = Get-ProjectSources -Project 'doomdll.vcxproj' -ListName 'ENGINE_SOURCES'
$gameSources = Get-ProjectSources -Project 'game.vcxproj' -ListName 'GAME_SOURCES'

$builder = New-Object System.Text.StringBuilder
[void]$builder.AppendLine('# Generated by scripts/gen-sources-win11-amd64.ps1 from the target copy''s')
[void]$builder.AppendLine('# idlib.vcxproj, doomdll.vcxproj and game.vcxproj. Do not edit by hand.')
[void]$builder.AppendLine('# Paths are relative to targets/win11-amd64/doom3/neo.')
[void]$builder.AppendLine()

function Add-CMakeList {
    param($Builder, [string]$Name, $Items)
    [void]$Builder.AppendLine("set($Name")
    foreach ($item in $Items) {
        [void]$Builder.AppendLine("    $item")
    }
    [void]$Builder.AppendLine(')')
    [void]$Builder.AppendLine()
}

Add-CMakeList -Builder $builder -Name 'IDLIB_SOURCES' -Items $idlibSources
Add-CMakeList -Builder $builder -Name 'ENGINE_SOURCES' -Items $engineSources
Add-CMakeList -Builder $builder -Name 'GAME_SOURCES' -Items $gameSources

$outDir = Split-Path -Parent $OutFile
if (-not (Test-Path -LiteralPath $outDir)) {
    New-Item -ItemType Directory -Path $outDir | Out-Null
}

[System.IO.File]::WriteAllText($OutFile, $builder.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Wrote $OutFile"
