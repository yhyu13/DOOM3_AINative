#Requires -Version 5.1
<#
.SYNOPSIS
    End-to-end cases for the material package toolchain: direct builds, tiled assembly and package
    source verification.

.DESCRIPTION
    Builds a throwaway fixture tree under out/toolchain-test/fixture/content/ (manifest, materials,
    sidecars and generated PNGs), then runs the real content/tools/build-material.ps1 and
    content/tools/verify-package.ps1 against it with -RepoRoot pointing at that fixture, exactly as
    tests/content/run-gates.ps1 does for the contract gate. No binary fixture is committed: the PNGs
    are generated by py -3 at run time.

    Cases:
      1. direct-build                 two builds share package_sha256, -Compare exits 0
      2. assembly-ok                  a 4096x4096 baseColor from four 2048 tiles records 4 sources
      3. assembly-gap                 one tile removed -> assembly-gap
      4. assembly-overlap             two tiles share an origin -> assembly-overlap
      5. assembly-ambiguous           path and assembly together -> channel-source-ambiguous
      6. verify-source-missing        a packaged tile deleted from the fixture -> source-missing
      7. verify-assembled-mismatch    assembled.height edited -> assembled-mismatch
      8. same-directory-compare       -Compare at -OutDir -> compare-same-directory

    Exits 0 only when all eight cases pass and prints TOOLCHAIN OK: <n> cases.

.PARAMETER RepoRoot
    Repository root. Defaults to the nearest ancestor of this script that holds .git.

.EXAMPLE
    powershell -NoProfile -File tests/content/run-toolchain.ps1
#>
[CmdletBinding()]
param(
    [string]$RepoRoot
)

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'

$libPath = Join-Path $PSScriptRoot '..\..\content\tools\content-lib.ps1'
if (-not (Test-Path -LiteralPath $libPath -PathType Leaf)) {
    Write-Host "TOOLCHAIN FAILED: shared library not found: $libPath"
    exit 1
}
. $libPath

if (-not $RepoRoot) {
    try {
        $RepoRoot = Get-RepoRoot -Start $PSScriptRoot
    } catch {
        Write-Host "TOOLCHAIN FAILED: cannot locate the repository root: $($_.Exception.Message)"
        exit 1
    }
}
$script:RepoRoot = [System.IO.Path]::GetFullPath($RepoRoot)
$script:Builder = Join-Path $script:RepoRoot 'content\tools\build-material.ps1'
$script:Verifier = Join-Path $script:RepoRoot 'content\tools\verify-package.ps1'
$script:WorkDir = Join-Path $script:RepoRoot 'out\toolchain-test'
$script:LogDir = Join-Path $script:WorkDir '_logs'
$script:Template = Join-Path $script:WorkDir '_template'
$script:Fixture = Join-Path $script:WorkDir 'fixture'
$script:GoodOut = $null

function Fail {
    param([string]$Message)
    Write-Host "TOOLCHAIN FAILED: $Message"
    exit 1
}

function Get-JsonField {
    param($Object, [string]$Name)
    if ($null -eq $Object) { return $null }
    $property = $Object.PSObject.Properties[$Name]
    if ($null -eq $property) { return $null }
    return $property.Value
}

if (-not (Test-Path -LiteralPath $script:Builder -PathType Leaf)) { Fail "builder not found: $($script:Builder)" }
if (-not (Test-Path -LiteralPath $script:Verifier -PathType Leaf)) { Fail "verifier not found: $($script:Verifier)" }
if (-not (Get-Command py -ErrorAction SilentlyContinue)) { Fail 'py -3 with Pillow is required to generate the fixture PNGs' }

if (Test-Path -LiteralPath $script:WorkDir) {
    Remove-Item -LiteralPath $script:WorkDir -Recurse -Force
}
New-Item -ItemType Directory -Path $script:LogDir -Force | Out-Null

$script:Failures = New-Object 'System.Collections.Generic.List[string]'

function Invoke-Child {
    param(
        [string]$FilePath,
        [string]$Arguments,
        [string]$OutFile,
        [string]$ErrFile
    )
    $process = Start-Process -FilePath $FilePath -ArgumentList $Arguments -NoNewWindow -Wait -PassThru `
        -RedirectStandardOutput $OutFile -RedirectStandardError $ErrFile
    return $process.ExitCode
}

function New-Result {
    param([int]$ExitCode, [string]$Output)
    return [pscustomobject]@{ ExitCode = $ExitCode; Output = $Output }
}

function Invoke-Build {
    param([string]$Case, [string]$Material, [string]$OutDir)
    $outFile = Join-Path $script:LogDir "$Case.build.out.txt"
    $errFile = Join-Path $script:LogDir "$Case.build.err.txt"
    $arguments = ('-NoProfile -ExecutionPolicy Bypass -File "{0}" -Material {1} -OutDir "{2}" -RepoRoot "{3}" -Force' -f `
            $script:Builder, $Material, $OutDir, $script:Fixture)
    $exitCode = Invoke-Child -FilePath 'powershell' -Arguments $arguments -OutFile $outFile -ErrFile $errFile
    $text = ''
    if (Test-Path -LiteralPath $outFile) { $text += [System.IO.File]::ReadAllText($outFile) }
    if (Test-Path -LiteralPath $errFile) { $text += [System.IO.File]::ReadAllText($errFile) }
    return New-Result -ExitCode $exitCode -Output $text
}

function Invoke-Verify {
    param([string]$Case, [string]$OutDir, [string]$Compare)
    $outFile = Join-Path $script:LogDir "$Case.verify.out.txt"
    $errFile = Join-Path $script:LogDir "$Case.verify.err.txt"
    $arguments = ('-NoProfile -ExecutionPolicy Bypass -File "{0}" -OutDir "{1}" -RepoRoot "{2}"' -f `
            $script:Verifier, $OutDir, $script:Fixture)
    if (-not [string]::IsNullOrWhiteSpace($Compare)) {
        $arguments += (' -Compare "{0}"' -f $Compare)
    }
    $exitCode = Invoke-Child -FilePath 'powershell' -Arguments $arguments -OutFile $outFile -ErrFile $errFile
    $text = ''
    if (Test-Path -LiteralPath $outFile) { $text += [System.IO.File]::ReadAllText($outFile) }
    if (Test-Path -LiteralPath $errFile) { $text += [System.IO.File]::ReadAllText($errFile) }
    return New-Result -ExitCode $exitCode -Output $text
}

function Test-Phrase {
    param($Result, [int]$ExpectedExit, [string]$Phrase)
    $phraseOk = ($Result.Output.IndexOf($Phrase, [System.StringComparison]::Ordinal) -ge 0)
    return (($Result.ExitCode -eq $ExpectedExit) -and $phraseOk)
}

function Report {
    param([string]$Name, [bool]$Passed, [string[]]$Details = @())
    if ($Passed) {
        Write-Host "$Name`: ok"
        return
    }
    Write-Host "$Name`: FAILED"
    foreach ($detail in $Details) { Write-Host "  $detail" }
    $script:Failures.Add($Name) | Out-Null
}

function New-Fixture {
    if (Test-Path -LiteralPath $script:Fixture) {
        Remove-Item -LiteralPath $script:Fixture -Recurse -Force
    }
    New-Item -ItemType Directory -Path $script:Fixture -Force | Out-Null
    Copy-Item -LiteralPath (Join-Path $script:Template 'content') -Destination (Join-Path $script:Fixture 'content') -Recurse -Force
}

# --- fixture template ----------------------------------------------------------------------------
New-Item -ItemType Directory -Path $script:Template -Force | Out-Null
$pythonFile = Join-Path $script:WorkDir 'make-fixtures.py'
$pythonSource = @'
import os
import sys
from PIL import Image

out = sys.argv[1]

def save(relative, size, color):
    path = os.path.join(out, relative)
    parent = os.path.dirname(path)
    if parent:
        os.makedirs(parent, exist_ok=True)
    Image.new("RGB", size, color).save(path, format="PNG")

save("content/hero/direct/baseColor.png", (128, 128), (48, 96, 160))
save("content/hero/assembly/baseColor_0_0.png", (2048, 2048), (90, 40, 40))
save("content/hero/assembly/baseColor_1_0.png", (2048, 2048), (40, 90, 40))
save("content/hero/assembly/baseColor_0_1.png", (2048, 2048), (40, 40, 90))
save("content/hero/assembly/baseColor_1_1.png", (2048, 2048), (90, 90, 40))
'@
[System.IO.File]::WriteAllText($pythonFile, $pythonSource + "`n", (New-Object System.Text.UTF8Encoding($false)))
& py -3 $pythonFile $script:Template
if ($LASTEXITCODE -ne 0) { Fail "py -3 could not generate the fixture PNGs (exit $LASTEXITCODE)" }

$q4 = [ordered]@{
    schema    = 'doom3-q4-material-set/1'
    materials = @(
        [ordered]@{ material = 'direct_fixture'; mtr = 'content/materials/direct_fixture.mtr'; cell = 'toolchain_direct' },
        [ordered]@{ material = 'assembly_fixture'; mtr = 'content/materials/assembly_fixture.mtr'; cell = 'toolchain_assembly' }
    )
}
Write-Json -Object $q4 -Path (Join-Path $script:Template 'content\manifest\q4-materials.json')
New-Item -ItemType Directory -Path (Join-Path $script:Template 'content\materials') -Force | Out-Null

$directMtr = @'
// Toolchain fixture material: a direct single-file source.
material direct_fixture
{
    {
        blend diffusemap
        map textures/toolchain/direct
    }
}
'@
$assemblyMtr = @'
// Toolchain fixture material: a tiled assembly source.
material assembly_fixture
{
    {
        blend diffusemap
        map textures/toolchain/assembly
    }
}
'@
[System.IO.File]::WriteAllText((Join-Path $script:Template 'content\materials\direct_fixture.mtr'), $directMtr, (New-Object System.Text.UTF8Encoding($false)))
[System.IO.File]::WriteAllText((Join-Path $script:Template 'content\materials\assembly_fixture.mtr'), $assemblyMtr, (New-Object System.Text.UTF8Encoding($false)))

function New-Unavailable {
    param([string]$Why)
    return [ordered]@{ state = 'unavailable'; why = $Why }
}
$directSidecar = [ordered]@{
    schema    = 'doom3-material-sidecar/1'
    material  = 'direct_fixture'
    mtr       = 'content/materials/direct_fixture.mtr'
    channels  = [ordered]@{
        baseColor = [ordered]@{ state = 'authored'; path = 'content/hero/direct/baseColor.png'; format = 'BC7_UNORM_SRGB'; srgb = $true }
        normal    = New-Unavailable 'toolchain fixture: normal is not authored'
        roughness = New-Unavailable 'toolchain fixture: roughness is not authored'
        metalness = New-Unavailable 'toolchain fixture: metalness is not authored'
        ao        = New-Unavailable 'toolchain fixture: ao is not authored'
        emissive  = New-Unavailable 'toolchain fixture: emissive is not authored'
    }
}
Write-Json -Object $directSidecar -Path (Join-Path $script:Template 'content\materials\direct_fixture.mat.json')

$assemblyTiles = @(
    [ordered]@{ path = 'content/hero/assembly/baseColor_0_0.png'; x = 0; y = 0 },
    [ordered]@{ path = 'content/hero/assembly/baseColor_1_0.png'; x = 2048; y = 0 },
    [ordered]@{ path = 'content/hero/assembly/baseColor_0_1.png'; x = 0; y = 2048 },
    [ordered]@{ path = 'content/hero/assembly/baseColor_1_1.png'; x = 2048; y = 2048 }
)
$assemblySidecar = [ordered]@{
    schema    = 'doom3-material-sidecar/1'
    material  = 'assembly_fixture'
    mtr       = 'content/materials/assembly_fixture.mtr'
    channels  = [ordered]@{
        baseColor = [ordered]@{
            state    = 'authored'
            format   = 'BC7_UNORM_SRGB'
            srgb     = $true
            assembly = [ordered]@{ width = 4096; height = 4096; tiles = $assemblyTiles }
        }
        normal    = New-Unavailable 'toolchain fixture: normal is not authored'
        roughness = New-Unavailable 'toolchain fixture: roughness is not authored'
        metalness = New-Unavailable 'toolchain fixture: metalness is not authored'
        ao        = New-Unavailable 'toolchain fixture: ao is not authored'
        emissive  = New-Unavailable 'toolchain fixture: emissive is not authored'
    }
}
Write-Json -Object $assemblySidecar -Path (Join-Path $script:Template 'content\materials\assembly_fixture.mat.json')

# --- case 1: direct build twice, byte-identical package ------------------------------------------
New-Fixture
$outA = Join-Path $script:WorkDir 'cases\direct-build\a'
$outB = Join-Path $script:WorkDir 'cases\direct-build\b'
$buildA = Invoke-Build -Case 'direct-build-a' -Material 'direct_fixture' -OutDir $outA
$buildB = Invoke-Build -Case 'direct-build-b' -Material 'direct_fixture' -OutDir $outB
$hashA = $null
$hashB = $null
if (Test-Path -LiteralPath (Join-Path $outA 'package.json')) {
    $hashA = [string](Get-JsonField (Read-Json (Join-Path $outA 'package.json')) 'package_sha256')
}
if (Test-Path -LiteralPath (Join-Path $outB 'package.json')) {
    $hashB = [string](Get-JsonField (Read-Json (Join-Path $outB 'package.json')) 'package_sha256')
}
$compareResult = Invoke-Verify -Case 'direct-build-compare' -OutDir $outA -Compare $outB
$directOk = ($buildA.ExitCode -eq 0) -and ($buildB.ExitCode -eq 0) -and
    (-not [string]::IsNullOrWhiteSpace($hashA)) -and ($hashA -ceq $hashB) -and
    (Test-Phrase $compareResult 0 'VERIFY OK')
Report -Name 'direct-build' -Passed $directOk -Details @(
    "build a exit $($buildA.ExitCode), build b exit $($buildB.ExitCode)",
    "package_sha256 a=$hashA b=$hashB",
    "compare exit $($compareResult.ExitCode)"
)

# --- case 2: tiled assembly builds and records its sources ---------------------------------------
New-Fixture
$assemblyOut = Join-Path $script:WorkDir 'cases\assembly-ok\out'
$assemblyBuild = Invoke-Build -Case 'assembly-ok' -Material 'assembly_fixture' -OutDir $assemblyOut
$assemblyVerify = Invoke-Verify -Case 'assembly-ok' -OutDir $assemblyOut
$sourceCount = 0
$assembledWidth = 0
$assembledHeight = 0
if (Test-Path -LiteralPath (Join-Path $assemblyOut 'package.json')) {
    $package = Read-Json (Join-Path $assemblyOut 'package.json')
    $texture = @(Get-JsonField $package 'textures')[0]
    $sourceCount = @(Get-JsonField $texture 'sources').Count
    $assembled = Get-JsonField $texture 'assembled'
    if ($null -ne $assembled) {
        $assembledWidth = [int](Get-JsonField $assembled 'width')
        $assembledHeight = [int](Get-JsonField $assembled 'height')
    }
}
$assemblyOk = ($assemblyBuild.ExitCode -eq 0) -and ($assemblyVerify.ExitCode -eq 0) -and
    ($sourceCount -eq 4) -and ($assembledWidth -eq 4096) -and ($assembledHeight -eq 4096)
Report -Name 'assembly-ok' -Passed $assemblyOk -Details @(
    "build exit $($assemblyBuild.ExitCode), verify exit $($assemblyVerify.ExitCode)",
    "sources=$sourceCount assembled=${assembledWidth}x${assembledHeight}"
)

# The good package is reused by the verification cases so only one 4K encode is paid.
$script:GoodOut = $assemblyOut

# --- case 8: comparing a package with itself is refused ------------------------------------------
$sameResult = Invoke-Verify -Case 'same-directory-compare' -OutDir $script:GoodOut -Compare $script:GoodOut
Report -Name 'same-directory-compare' -Passed (Test-Phrase $sameResult 1 'compare-same-directory') -Details @(
    "exit $($sameResult.ExitCode)"
)

# --- case 6: a packaged tile deleted from the fixture --------------------------------------------
if (-not (Test-Path -LiteralPath (Join-Path $script:GoodOut 'package.json'))) {
    Report -Name 'verify-source-missing' -Passed $false -Details @('assembly-ok produced no package to copy')
} else {
    New-Fixture
    $missingCase = Join-Path $script:WorkDir 'cases\verify-source-missing'
    New-Item -ItemType Directory -Path $missingCase -Force | Out-Null
    $missingOut = Join-Path $missingCase 'out'
    Copy-Item -LiteralPath $script:GoodOut -Destination $missingOut -Recurse -Force
    Remove-Item -LiteralPath (Join-Path $script:Fixture 'content\hero\assembly\baseColor_1_1.png') -Force
    $missingResult = Invoke-Verify -Case 'verify-source-missing' -OutDir $missingOut
    Report -Name 'verify-source-missing' -Passed (Test-Phrase $missingResult 1 'source-missing') -Details @(
        "exit $($missingResult.ExitCode)"
    )
}

# --- case 7: assembled size edited in package.json -----------------------------------------------
if (-not (Test-Path -LiteralPath (Join-Path $script:GoodOut 'package.json'))) {
    Report -Name 'verify-assembled-mismatch' -Passed $false -Details @('assembly-ok produced no package to copy')
} else {
    New-Fixture
    $mismatchCase = Join-Path $script:WorkDir 'cases\verify-assembled-mismatch'
    New-Item -ItemType Directory -Path $mismatchCase -Force | Out-Null
    $mismatchOut = Join-Path $mismatchCase 'out'
    Copy-Item -LiteralPath $script:GoodOut -Destination $mismatchOut -Recurse -Force
    $mismatchPackagePath = Join-Path $mismatchOut 'package.json'
    $mismatchPackage = Read-Json $mismatchPackagePath
    $mismatchTexture = @(Get-JsonField $mismatchPackage 'textures')[0]
    $mismatchTexture.assembled.height = 2048
    Write-Json -Object $mismatchPackage -Path $mismatchPackagePath
    $mismatchResult = Invoke-Verify -Case 'verify-assembled-mismatch' -OutDir $mismatchOut
    Report -Name 'verify-assembled-mismatch' -Passed (Test-Phrase $mismatchResult 1 'assembled-mismatch') -Details @(
        "exit $($mismatchResult.ExitCode)"
    )
}

# --- case 3: one tile removed leaves a gap ------------------------------------------------------
New-Fixture
$gapSidecarPath = Join-Path $script:Fixture 'content\materials\assembly_fixture.mat.json'
$gapSidecar = Read-Json $gapSidecarPath
$gapTiles = @($gapSidecar.channels.baseColor.assembly.tiles)
$gapSidecar.channels.baseColor.assembly.tiles = @($gapTiles[0], $gapTiles[1], $gapTiles[2])
Write-Json -Object $gapSidecar -Path $gapSidecarPath
$gapResult = Invoke-Build -Case 'assembly-gap' -Material 'assembly_fixture' -OutDir (Join-Path $script:WorkDir 'cases\assembly-gap\out')
Report -Name 'assembly-gap' -Passed (Test-Phrase $gapResult 1 'assembly-gap') -Details @(
    "exit $($gapResult.ExitCode)"
)

# --- case 4: two tiles share an origin ----------------------------------------------------------
New-Fixture
$overlapSidecarPath = Join-Path $script:Fixture 'content\materials\assembly_fixture.mat.json'
$overlapSidecar = Read-Json $overlapSidecarPath
$overlapTiles = @($overlapSidecar.channels.baseColor.assembly.tiles)
$overlapTiles[3].x = 0
$overlapTiles[3].y = 0
Write-Json -Object $overlapSidecar -Path $overlapSidecarPath
$overlapResult = Invoke-Build -Case 'assembly-overlap' -Material 'assembly_fixture' -OutDir (Join-Path $script:WorkDir 'cases\assembly-overlap\out')
Report -Name 'assembly-overlap' -Passed (Test-Phrase $overlapResult 1 'assembly-overlap') -Details @(
    "exit $($overlapResult.ExitCode)"
)

# --- case 5: a channel declares both path and assembly ------------------------------------------
New-Fixture
$ambiguousSidecarPath = Join-Path $script:Fixture 'content\materials\assembly_fixture.mat.json'
$ambiguousSidecar = Read-Json $ambiguousSidecarPath
$ambiguousSidecar.channels.baseColor | Add-Member -NotePropertyName path -NotePropertyValue 'content/hero/assembly/baseColor_0_0.png'
Write-Json -Object $ambiguousSidecar -Path $ambiguousSidecarPath
$ambiguousResult = Invoke-Build -Case 'assembly-ambiguous' -Material 'assembly_fixture' -OutDir (Join-Path $script:WorkDir 'cases\assembly-ambiguous\out')
Report -Name 'assembly-ambiguous' -Passed (Test-Phrase $ambiguousResult 1 'channel-source-ambiguous') -Details @(
    "exit $($ambiguousResult.ExitCode)"
)

if ($script:Failures.Count -gt 0) {
    Write-Host "TOOLCHAIN FAILED: $($script:Failures.Count) case(s):"
    foreach ($failure in $script:Failures) { Write-Host " - $failure" }
    exit 1
}

Write-Host 'TOOLCHAIN OK: 8 cases'
exit 0
